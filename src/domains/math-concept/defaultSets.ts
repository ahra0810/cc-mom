import type { QuestionSet, SetSlots, MathConceptMeta } from '../../types/sets';
import type { Question, Difficulty } from '../../types';
import { withMcAnswerAt } from '../../services/mcShuffle';

const now = Date.now();

type RT = [emoji: string, term: string, desc: string];

interface CS {
  term: string;
  hanja?: string;        // 한자어만 (혼합어·순우리말은 생략 → '')
  eng: string;
  engOrigin?: string;
  tdef: string;          // 교과서 정의
  def: string;           // 친근한 정의
  emoji: string;         // visualEmoji (Gowun Dodum, **강조** 1~2개, ≤5줄)
  ex: string;            // visualExample (\n 으로 3~4줄)
  rel: [RT, RT, RT];     // 비슷한/관련 개념 3개
  tbx: string;           // 실제 발문 예
  g: number;             // 학년 (1~6 초, 7=중1, 8=중2, 9=중3)
  diff: Difficulty;
  tags: string[];
  q1: [string, string, string, string]; // 정의 묻기 보기
  q1a: string;           // 정답 (q1 중 하나)
  q1e: string;           // 해설
  q2: [string, string, string, string]; // 발문 속 의미 보기
  q2a: string;
  q2e: string;
}

let qSeq = 0;
let mcSeq = 0;
function q(partial: Omit<Question, 'id' | 'createdAt' | 'source' | 'subjectId'>): Question {
  qSeq++;
  const built: Question = {
    id: `seed-mc-q-${qSeq.toString().padStart(3, '0')}`,
    subjectId: 'math-concept',
    createdAt: now,
    source: 'preset',
    ...partial,
  };
  if (built.type === 'multiple-choice') {
    const positioned = withMcAnswerAt(built, mcSeq);
    mcSeq++;
    return positioned;
  }
  return built;
}

let setSeq = 0;
function buildSet(c: CS): QuestionSet {
  setSeq++;
  const meta: MathConceptMeta = {
    domain: 'math-concept',
    term: c.term,
    hanja: c.hanja || '',
    englishTerm: c.eng,
    ...(c.engOrigin ? { englishOrigin: c.engOrigin } : {}),
    textbookDefinition: c.tdef,
    definition: c.def,
    visualEmoji: c.emoji,
    visualExample: c.ex,
    relatedTerms: c.rel.map((r) => r[1]),
    relatedTermsDetailed: c.rel.map((r) => ({ emoji: r[0], term: r[1], desc: r[2] })),
    textbookExample: c.tbx,
    grade: c.g,
  };
  const slots = [
    q({
      type: 'multiple-choice', difficulty: c.diff,
      question: `"${c.term}"을(를) 가장 쉽게 풀어쓴 설명은?`,
      options: [...c.q1],
      answer: c.q1a,
      explanation: c.q1e,
    }),
    q({
      type: 'multiple-choice', difficulty: c.diff,
      question: `🔍 다음 수학 문제에서 "${c.term}"이(가) 의미하는 것은?\n\n[문제] ${c.tbx}`,
      options: [...c.q2],
      answer: c.q2a,
      explanation: c.q2e,
    }),
  ] as unknown as SetSlots;

  return {
    id: `seed-mc-${setSeq}`,
    title: `${c.term} 학습지`,
    domain: 'math-concept',
    difficulty: c.diff,
    meta,
    slots,
    tags: c.tags,
    createdAt: now,
    updatedAt: now,
    source: 'preset',
  };
}

